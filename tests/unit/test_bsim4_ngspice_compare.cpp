class BSIM4ExactCompareTest : public ::testing::Test {
protected:
    void SetUp() override {
        // Setup BSIM4 parameters matching /tmp/bsim4_compare_exact.sp
        params_.w = 10e-6;   // W=10um
        params_.l = 45e-9;   // L=45nm
        params_.toxe = 1.25e-9;
        params_.toxp = 1.25e-9;

        // Threshold voltage parameters
        params_.vth0 = 0.45;
        params_.k1 = 0.53;
        params_.k2 = 0.02;

        // SCE parameters (enabled for this test)
        params_.dvt0 = 2.2;
        params_.dvt1 = 0.53;
        params_.dvt2 = -0.032;

        // Mobility parameters
        params_.u0 = 0.045;
        params_.ua = 1e-9;
        params_.ub = 1e-18;
        params_.uc = -1e-10;

        // Saturation velocity
        params_.vsat = 8.5e4;

        // CLM
        params_.pclm = 1.3;

        // Channel doping
        params_.ndep = 1.7e17;
        params_.xj = 1.5e-7;

        // LPE (disabled)
        params_.lpe0 = 0.0;
        params_.lpeb = 0.0;

        // Subthreshold parameters
        params_.nfactor = 1.5;
        params_.cdsc = 0.00024;
        params_.voff = -0.08;

        // Temperature coefficients
        params_.kt1 = -0.11;
        params_.kt2 = 0.022;
        params_.ute = -1.5;

        // DIBL parameters
        params_.eta0 = 0.08;
        params_.etab = -0.07;
        params_.dsub = 0.56;
        params_.drout = 0.56;
        params_.pdiblc1 = 0.39;
        params_.pdiblc2 = 0.0086;

        // Nominal temperature
        params_.tnom = 300.15;  // 27°C

        // Compute derived parameters
        params_.compute_derived_params(params_.tnom);
    }

    BSIM4Params params_;
};

TEST_F(BSIM4ExactCompareTest, W10um_L45nm_Vgs1V_Vds0p5V) {
    BSIM4Core core(params_, false);  // N-channel

    const Real temp_k = 300.15;  // 27°C
    const Real theta0vb0 = 1.0;
    const Real vgs = 1.0;
    const Real vds = 0.5;
    const Real vbs = 0.0;

    auto op = core.evaluate(vgs, vds, vbs, 0.0, temp_k, theta0vb0);

    // ngspice reference values from /tmp/bsim4_detail.sp
    const Real ngspice_vth = 0.2588432;
    const Real ngspice_vdsat = 0.3950335;
    const Real ngspice_gm = 9.487115e-3;
    const Real ngspice_gds = 9.395330e-3;
    const Real ngspice_ids = 8.93974e-3;
    const Real ngspice_vgsteff = 0.7411538;
    const Real ngspice_vdseff = 0.3673425;

    std::cout << "\n=== BSIM4 Exact Comparison: W=10um, L=45nm ===" << std::endl;
    std::cout << "Condition: Vgs=1.0V, Vds=0.5V, Vbs=0V, T=27°C" << std::endl;
    std::cout << std::endl;

    std::cout << std::setw(14) << "Parameter"
              << std::setw(14) << "KirimaSpice"
              << std::setw(14) << "ngspice"
              << std::setw(12) << "Error[%]"
              << std::endl;
    std::cout << std::string(54, '-') << std::endl;

    auto print_compare = [](const char* name, Real kirimaspice, Real ngspice) {
        Real err = (ngspice != 0.0) ? (kirimaspice - ngspice) / ngspice * 100.0 : 0.0;
        std::cout << std::fixed << std::setprecision(6)
                  << std::setw(14) << name
                  << std::setw(14) << kirimaspice
                  << std::setw(14) << ngspice
                  << std::setprecision(1)
                  << std::setw(12) << std::showpos << err << "%" << std::noshowpos
                  << std::endl;
        return err;
    };

    Real err_vth = print_compare("Vth [V]", op.vth, ngspice_vth);
    Real err_vdsat = print_compare("Vdsat [V]", op.vdsat, ngspice_vdsat);
    Real err_gm = print_compare("gm [S]", op.gm, ngspice_gm);
    Real err_gds = print_compare("gds [S]", op.gds, ngspice_gds);
    Real err_ids = print_compare("Ids [A]", op.ids, ngspice_ids);

    std::cout << std::endl;
    std::cout << "=== Summary ===" << std::endl;

    // Check if key parameters are within acceptable range
    bool vth_ok = std::abs(err_vth) < 30.0;
    bool vdsat_ok = std::abs(err_vdsat) < 30.0;
    bool gm_ok = std::abs(err_gm) < 50.0;
    bool gds_ok = std::abs(err_gds) < 50.0;
    bool ids_ok = std::abs(err_ids) < 50.0;

    std::cout << "Vth:   " << (vth_ok ? "OK" : "FAIL") << " (err=" << err_vth << "%)" << std::endl;
    std::cout << "Vdsat: " << (vdsat_ok ? "OK" : "FAIL") << " (err=" << err_vdsat << "%)" << std::endl;
    std::cout << "gm:    " << (gm_ok ? "OK" : "FAIL") << " (err=" << err_gm << "%)" << std::endl;
    std::cout << "gds:   " << (gds_ok ? "OK" : "FAIL") << " (err=" << err_gds << "%)" << std::endl;
    std::cout << "Ids:   " << (ids_ok ? "OK" : "FAIL") << " (err=" << err_ids << "%)" << std::endl;

    // Relaxed assertions for initial validation
    EXPECT_LT(std::abs(err_vth), 30.0) << "Vth error exceeds 30%";
    EXPECT_LT(std::abs(err_vdsat), 30.0) << "Vdsat error exceeds 30%";
    // gm/gds/Ids may have larger errors due to scaling calibration
    EXPECT_LT(std::abs(err_ids), 100.0) << "Ids error exceeds 100%";
}
